export type SqlDialect = 'sqlite' | 'postgres';

export type ColumnPlan = {
  id: string;
  timestamp: string;
  boolean: string;
  json: string;
  date: string;
};

export function columnPlan(dialect: SqlDialect): ColumnPlan {
  if (dialect === 'postgres') {
    return {
      id: 'integer generated by default as identity',
      timestamp: 'timestamptz',
      boolean: 'boolean',
      json: 'jsonb',
      date: 'date',
    };
  }

  return {
    id: 'integer primary key',
    timestamp: 'integer',
    boolean: 'integer',
    json: 'text',
    date: 'text',
  };
}
